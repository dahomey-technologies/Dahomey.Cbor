        [InlineData("C482000A", "10", 0)]
        [InlineData("C4820101", "1", 1)]
        [InlineData("C48220182D", "45", -1)]                         // 4.5
        [InlineData("C482002B", "-12", 0)]
        [InlineData("C48221C249010000000000000000", "18446744073709551616", -2)]
        public void ReadDecimalFraction(string hexBuffer, string mantissa, int exponent)
        {
            Helper.TestRead(hexBuffer, new CborDecimalFraction(BigInteger.Parse(mantissa), exponent));
        }

        [Theory]
        [InlineData("C5822003", "3", -1)]              // 1.5, RFC 8949 section 3.4.4
        [InlineData("C5820000", "0", 0)]
        [InlineData("C58200C249010000000000000000", "18446744073709551616", 0)]
