    /// <summary>
    /// The two RFC 8949 §3.4.4 types, <see cref="CborDecimalFraction"/> (tag 4) and
    /// <see cref="CborBigFloat"/> (tag 5). The hex buffers for <c>273.15</c> and <c>1.5</c> are the ones
    /// §3.4.4 spells out.
    /// </summary>
    /// <remarks>
    /// <c>DecimalFractionTests</c> is the neighbouring file and covers the other half of tag 4: what a
    /// member typed <see cref="decimal"/> writes under <c>CborOptions.DecimalFormat</c> and reads back.
    /// The two agree on the bytes and differ in what they can hold, which
    /// <see cref="ADecimalMemberAndAFractionMemberWriteTheSameBytes"/> pins.
    /// </remarks>
    public class FractionTypeTests
    {
        public class ObjectWithFractions
        {
            [CborProperty("p")]
            public CborDecimalFraction Price { get; set; }

            [CborProperty("s")]
            public CborBigFloat Scale { get; set; }
        }

        [Theory]
        [InlineData("C48221196AB3", "27315", -2)]      // 273.15, RFC 8949 section 3.4.4
