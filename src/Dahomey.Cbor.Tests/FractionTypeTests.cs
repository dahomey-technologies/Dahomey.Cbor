        /// </summary>
        /// <remarks>
        /// Asserted rather than inferred from where the dispatch happens. The two encodings arrived
        /// separately -- the <see cref="decimal"/> half in #206, these types in #170 -- so nothing else
        /// holds them to one wire form, and a divergence would be invisible to either file's own tests.
        /// </remarks>
        [Fact]
        public void ADecimalMemberAndAFractionMemberWriteTheSameBytes()
        {
            CborOptions options = new CborOptions { DecimalFormat = DecimalFormat.DecimalFraction };

            Assert.Equal(
                Helper.Write(273.15m, options),
                Helper.Write(new CborDecimalFraction(27315, -2)),
                ignoreCase: true);

            // And each reads the other's bytes, as far as its own type reaches.
            Assert.Equal(273.15m, Helper.Read<decimal>("C48221196AB3", options));
            Assert.Equal(new CborDecimalFraction(27315, -2), Helper.Read<CborDecimalFraction>("C48221196AB3"));
        }

        /// <summary>
        /// Both encodings of tag 4 in one document: a <see cref="decimal"/> member beside a
        /// <see cref="CborDecimalFraction"/> and a <see cref="CborBigFloat"/> one, written and read back
        /// together.
        /// </summary>
        /// <remarks>
        /// <see cref="ADecimalMemberAndAFractionMemberWriteTheSameBytes"/> writes the two separately,
        /// which settles the bytes but not the cohabitation: it never has both converters registered
        /// against one object mapping at once. The value of doing it in a single type is that the
        /// members are resolved together, so a provider that answered for the wrong one would show up
        /// here and nowhere else.
        /// </remarks>
        [Fact]
        public void ADecimalAndTheFractionTypesCoexistInOneObject()
        {
            CborOptions options = new CborOptions { DecimalFormat = DecimalFormat.DecimalFraction };

            GeneratedMixedHolder holder = new GeneratedMixedHolder
            {
                Plain = 273.15m,
                Fraction = new CborDecimalFraction(27315, -2),
                Big = new CborBigFloat(3, -1),
            };

            // The decimal and the fraction are the same six bytes, twice over, under different names.
            Assert.Equal(
                "A36164C48221196AB36166C48221196AB36162C5822003",
                Helper.Write(holder, options),
                ignoreCase: true);

            GeneratedMixedHolder read = Helper.Read<GeneratedMixedHolder>(Helper.Write(holder, options), options);

            Assert.Equal(holder.Plain, read.Plain);
            Assert.Equal(holder.Fraction, read.Fraction);
            Assert.Equal(holder.Big, read.Big);
        }

        /// <summary>
        /// <c>CborOptions.DecimalFormat</c> governs the <see cref="decimal"/> member and nothing else.
        /// Under the default the decimal goes back to the <c>FC</c> form while the two struct members
        /// stay on tags 4 and 5, in the same document.
        /// </summary>
        /// <remarks>
        /// This is the assertion behind "neither shadows the other". The two mechanisms select on
        /// different things -- an option for the one, the declared type for the others -- and the way
        /// that would break is the option leaking across, which only shows when one document contains
        /// both and the option is set the way that makes them differ.
        /// </remarks>
        [Fact]
        public void TheDecimalFormatDoesNotReachTheFractionTypes()
        {
            GeneratedMixedHolder holder = new GeneratedMixedHolder
            {
                Plain = 273.15m,
                Fraction = new CborDecimalFraction(27315, -2),
                Big = new CborBigFloat(3, -1),
            };

            Assert.Equal(
                "A36164FC0000000000006AB300000000000200006166C48221196AB36162C5822003",
                Helper.Write(holder),
                ignoreCase: true);

            GeneratedMixedHolder read = Helper.Read<GeneratedMixedHolder>(Helper.Write(holder));

            Assert.Equal(holder.Plain, read.Plain);
            Assert.Equal(holder.Fraction, read.Fraction);
            Assert.Equal(holder.Big, read.Big);
        }

        /// <summary>
        /// The three members round-trip together under <c>CborOptions.Deterministic</c>, where the map
        /// keys are reordered and the bytes are the ones the ordering was computed over.
        /// </summary>
        [Fact]
        public void TheFractionTypesCoexistUnderDeterministic()
        {
            CborOptions options = new CborOptions
            {
                DecimalFormat = DecimalFormat.DecimalFraction,
                Deterministic = true,
            };

            GeneratedMixedHolder holder = new GeneratedMixedHolder
            {
                Plain = 273.15m,
                Fraction = new CborDecimalFraction(27315, -2),
                Big = new CborBigFloat(3, -1),
            };

            // Keys in length-then-bytewise order: "b", "d", "f".
            Assert.Equal(
                "A36162C58220036164C48221196AB36166C48221196AB3",
                Helper.Write(holder, options),
                ignoreCase: true);

            GeneratedMixedHolder read = Helper.Read<GeneratedMixedHolder>(Helper.Write(holder, options), options);

            Assert.Equal(holder.Plain, read.Plain);
            Assert.Equal(holder.Fraction, read.Fraction);
            Assert.Equal(holder.Big, read.Big);
        }

        /// <summary>
        /// The cohabitation holds on the generated path too, with both settings.
        /// </summary>
        /// <remarks>
        /// The half a run-time test cannot reach, and the two mechanisms are independent there in a way
        /// they are not at run time: <c>TypeCollector</c> decides that the two structs are primitives,
        /// while <c>DecimalFormat</c> travels from the attribute into the emitted registrations. A
        /// generated context could get either right and the other wrong -- collecting the structs as
        /// objects, or dropping the setting -- and the reflection bytes are what catches both, since
        /// they are the same document by construction.
        /// </remarks>
        [Fact]
        public void TheGeneratedPathAgreesOnBothEncodingsOfTagFour()
        {
            GeneratedMixedHolder holder = new GeneratedMixedHolder
            {
                Plain = 273.15m,
                Fraction = new CborDecimalFraction(27315, -2),
                Big = new CborBigFloat(3, -1),
            };

            MixedFractionContext fractionContext = new MixedFractionContext();
            CborOptions fractionOptions = new CborOptions { DecimalFormat = DecimalFormat.DecimalFraction };

            Assert.Equal(
                Helper.Write(holder, fractionOptions),
                Helper.Write(holder, fractionContext.Options),
                ignoreCase: true);

            MixedDefaultContext defaultContext = new MixedDefaultContext();

            Assert.Equal(
                Helper.Write(holder),
                Helper.Write(holder, defaultContext.Options),
                ignoreCase: true);

            // And back, through the generated readers rather than the reflection ones.
            GeneratedMixedHolder read = Helper.Read<GeneratedMixedHolder>(
                Helper.Write(holder, fractionContext.Options), fractionContext.Options);

            Assert.Equal(holder.Plain, read.Plain);
            Assert.Equal(holder.Fraction, read.Fraction);
            Assert.Equal(holder.Big, read.Big);
        }

        /// <summary>
        /// One document, two ways of asking for a <see cref="decimal"/>, one answer. A tag 4 read into a
        /// <see cref="decimal"/> member goes through <c>CborReader</c>'s own conversion; the same bytes
        /// read into this type and then converted go through <see cref="CborDecimalFraction.ToDecimal"/>.
        /// Both are exact-or-refuse, and they have to agree on which.
        /// </summary>
        /// <remarks>
        /// A differential test rather than two tables of expectations, because the two implementations
        /// arrived separately -- #206 and #170 -- and nothing else holds them together. It caught a real
        /// divergence: <c>[-1, 10^29]</c> is <c>1E+28</c>, which a <see cref="decimal"/> holds once the
        /// scale is given back to the mantissa's width, and only the reader did that. The exception types
        /// differ by design and are not compared: a read failure is a <see cref="CborException"/>, a
        /// conversion failure an <see cref="OverflowException"/>.
        /// </remarks>
        [Theory]
        [InlineData("27315", -2)]
        [InlineData("-27315", -2)]
        // Inside the scale limit and too wide, so the width is fixed by giving the scale back.
        [InlineData("100000000000000000000000000000", -1)]
        [InlineData("10000000000000000000000000000000", -3)]
        // Past the scale limit, with trailing zeros to give back.
        [InlineData("1000", -30)]
        // Neither is available: refused by both.
        [InlineData("3", -29)]
        [InlineData("79228162514264337593543950336", 0)]
        public void ADecimalMemberAndToDecimalAgree(string mantissaText, int exponent)
        {
            BigInteger mantissa = BigInteger.Parse(mantissaText);
            CborDecimalFraction fraction = new CborDecimalFraction(mantissa, exponent);
            string hexBuffer = Helper.Write(fraction);

            decimal? read = null;
            decimal? converted = null;

            try
            {
                read = Helper.Read<decimal>(hexBuffer);
            }
            catch (CborException)
            {
            }

            try
            {
                converted = fraction.ToDecimal();
            }
            catch (OverflowException)
            {
            }

            Assert.Equal(read, converted);
        }

        /// <summary>
        /// Nothing about the object model changes: a tag 4 still reads into a <c>CborValue</c> as the
        /// two-element array it is encoded as, and the tag still survives the write, as it has since
        /// #165. Only a member <em>typed</em> as one of these structs gains semantics.
        /// </summary>
        [Fact]
        public void TheObjectModelStillSeesADecimalFractionAsATaggedArray()
        {
            ObjectModel.CborValue value = Helper.Read<ObjectModel.CborValue>("C48221196AB3");

            Assert.Equal(ObjectModel.CborValueType.Array, value.Type);
            Assert.Equal("C48221196AB3", Helper.Write(value), ignoreCase: true);
        }

        [Fact]
        public void GeneratedContextRoundTrip()
        {
            FractionContext context = new FractionContext();

            GeneratedFractionHolder holder = new GeneratedFractionHolder
            {
                Price = new CborDecimalFraction(27315, -2),
                Scale = new CborBigFloat(3, -1),
                Optional = new CborDecimalFraction(BigInteger.Parse("18446744073709551616"), -3),
            };

            string hexBuffer = Helper.Write(holder, context.Options);
            GeneratedFractionHolder read = Helper.Read<GeneratedFractionHolder>(hexBuffer, context.Options);

            Assert.Equal(holder.Price, read.Price);
            Assert.Equal(holder.Scale, read.Scale);
            Assert.Equal(holder.Optional, read.Optional);

            // The bytes the reflection path writes, which is the assertion that catches the two types
            // being collected as objects rather than as primitives.
            Assert.Equal(hexBuffer, Helper.Write(holder), ignoreCase: true);
        }
