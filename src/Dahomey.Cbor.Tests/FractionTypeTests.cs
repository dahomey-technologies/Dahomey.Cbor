        /// <summary>
        /// A mantissa the size of a real document, reduced in one division rather than one per digit.
        /// </summary>
        /// <remarks>
        /// The size is the test. Each big-integer division is O(n) in the mantissa, so giving digits back
        /// one at a time is quadratic in the size of the document the mantissa came from: measured on
        /// net10.0, 40,000 digits took 513 ms that way, 80,000 took 2.0 s and 160,000 took 8.0 s, against
        /// 3, 3 and 11 ms bounded. The same shape reaches <see cref="CborBigFloat"/> through
        /// <c>2^k × 2^-k</c>, which is why both are here. An application calling either conversion on a
        /// value it decoded is the ordinary thing to do, so the amplification is reachable from a
        /// document.
        /// </remarks>
        [Fact]
        public void AMantissaWithManyTrailingZerosReducesInOneStep()
        {
            BigInteger tenToThe100000 = BigInteger.Pow(10, 100000);

            Assert.Equal(1e-28m, new CborDecimalFraction(tenToThe100000, -100028).ToDecimal());
            Assert.Equal(1m, new CborBigFloat(BigInteger.Pow(2, 100000), -100000).ToDecimal());
            Assert.Equal(1.0, new CborBigFloat(BigInteger.Pow(2, 100000), -100000).ToDouble());

            // And a digit that is not zero still refuses, rather than the reduction quietly dropping it.
            Assert.Throws<OverflowException>(() => new CborDecimalFraction(tenToThe100000 + 1, -100028).ToDecimal());
        }

        /// <summary>
        /// A <see cref="double"/> converted to a fraction and back is the same <see cref="double"/>, at
        /// any mantissa width. Padding the mantissa with zeros and lowering the exponent leaves the
        /// value alone, so the expected answer is known however long the digits run.
        /// </summary>
        /// <remarks>
        /// The padding is what makes this a test of long mantissas with a knowable answer, rather than
        /// one that has to trust another conversion to say what the answer is. It covers both ends of
        /// the range: <see cref="double.Epsilon"/> and the value below the smallest normal exercise the
        /// subnormal grid, where the rounding position is set by 2^-1074 rather than by 53 significant
        /// bits, and <see cref="double.MaxValue"/> exercises the top without tipping into the overflow
        /// check.
        /// </remarks>
        [Theory]
        [InlineData(0.1, 0)]
        [InlineData(0.1, 2000)]
        [InlineData(1.5, 0)]
        [InlineData(1.5, 2000)]
        [InlineData(-273.15, 500)]
        [InlineData(double.MaxValue, 0)]
        [InlineData(double.MaxValue, 400)]
        [InlineData(double.Epsilon, 0)]
        [InlineData(double.Epsilon, 500)]
        [InlineData(2.2250738585072014E-308, 300)]   // the smallest normal
        [InlineData(1E-320, 300)]                    // subnormal
        public void ADoubleSurvivesAFractionOfAnyWidth(double value, int padding)
        {
            CborDecimalFraction fraction = (CborDecimalFraction)value;
            CborDecimalFraction padded = new CborDecimalFraction(
                fraction.Mantissa * BigInteger.Pow(10, padding), fraction.Exponent - padding);

            Assert.Equal(value, padded.ToDouble());
        }

        /// <summary>
        /// The conversion agrees with the platform's own parser over a spread of ordinary values, which
        /// is the oracle for everything the cases above do not name individually.
        /// </summary>
        /// <remarks>
        /// Deliberately kept to modest digit counts. <c>double.Parse</c> is only trustworthy as an
        /// oracle where every framework version agrees with it, and .NET 8 does not: a 1,201-digit
        /// mantissa at <c>E-1200</c> — a value just above 1.0 — parses there as <em>zero</em>, where
        /// .NET 9 and .NET 10 are right. That is why this type does its own arithmetic rather than
        /// rendering and parsing, and why the oracle is used only where it can be trusted.
        /// </remarks>
        [Fact]
        public void OrdinaryValuesAgreeWithThePlatformParser()
        {
            Random random = new Random(20260813);

            for (int iteration = 0; iteration < 2000; iteration++)
            {
                BigInteger mantissa = new BigInteger(random.NextInt64());
                int exponent = random.Next(-25, 26);

                string rendered = mantissa.ToString(CultureInfo.InvariantCulture)
                    + "E" + exponent.ToString(CultureInfo.InvariantCulture);
                double expected = double.Parse(rendered, NumberStyles.Float, CultureInfo.InvariantCulture);

                Assert.Equal(expected, new CborDecimalFraction(mantissa, exponent).ToDouble());
            }
        }

        /// <summary>
        /// The case the cap's trailing marker exists for: a value a hair above the midpoint between two
        /// doubles, where the hair is further out than the cap keeps.
        /// </summary>
        /// <remarks>
        /// The midpoint itself is exactly representable as a decimal fraction — it is an odd multiple of
        /// a power of two, and <c>2^-n = 5^n × 10^-n</c> — and rounds to even, which is <c>1.0</c> here.
        /// Adding one unit 2,000 digits further down leaves a value that must round the other way, to
        /// the double above. A truncation that dropped those digits silently would land back on the
        /// midpoint and round to even, one ulp low; the appended non-zero digit is what prevents it.
        /// </remarks>
        [Fact]
        public void AValueJustAboveAMidpointStillRoundsAwayFromIt()
        {
            // The double above 1.0 is 1 + 2^-52, so the midpoint is 1 + 2^-53 = (2^53 + 1) * 2^-53.
            // Built as a decimal fraction rather than through a double, so nothing has rounded yet:
            // (2^53 + 1) * 5^53 * 10^-53 is that value exactly.
            const int binaryExponent = 53;
            BigInteger midpointMantissa =
                ((BigInteger.One << binaryExponent) + 1) * BigInteger.Pow(5, binaryExponent);
            int midpointExponent = -binaryExponent;

            // Exactly on the midpoint: ties go to even, and 1.0 is the even one.
            Assert.Equal(1.0, new CborDecimalFraction(midpointMantissa, midpointExponent).ToDouble());

            // One unit 2,000 decimal places below that, which is well past the cap: the value is above
            // the midpoint and must round to the double above.
            BigInteger justAbove = midpointMantissa * BigInteger.Pow(10, 2000) + 1;

            Assert.Equal(
                Math.BitIncrement(1.0),
                new CborDecimalFraction(justAbove, midpointExponent - 2000).ToDouble());

            // The same construction one unit below the midpoint rounds down to 1.0, which is the
            // assertion that fails if the marker is appended unconditionally rather than only when
            // something was dropped.
            BigInteger justBelow = midpointMantissa * BigInteger.Pow(10, 2000) - 1;

            Assert.Equal(1.0, new CborDecimalFraction(justBelow, midpointExponent - 2000).ToDouble());
        }

